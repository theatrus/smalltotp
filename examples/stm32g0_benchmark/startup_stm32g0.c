void Reset_Handler(void) {
    uint32_t *src, *dst;

    /* Copy data from flash to RAM */
    src = &_sidata;
    dst = &_sdata;
    while (dst < &_edata) {
        *dst++ = *src++;
    }

    /* Zero BSS */
    dst = &_sbss;
    while (dst < &_ebss) {
        *dst++ = 0;
    }

    /* Call main */
    main();

    /* Loop forever if main returns */
    while (1);
}

void Default_Handler(void) {
    while (1);
}
